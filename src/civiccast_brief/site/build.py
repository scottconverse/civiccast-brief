"""Build the static site: read the episodes directory, write every page, the feed and the search index."""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from civiccast_brief.site import images, seo, stills
from civiccast_brief.site.feed import artwork_path, build_feed
from civiccast_brief.site.model import InputError, SiteInput, load_site_input
from civiccast_brief.site.pages import (
    FAVICON_PNG,
    ROBOTS_PATH,
    SEARCH_INDEX_PATH,
    SITEMAP_PATH,
    build_pages,
)
from civiccast_brief.site.render import make_environment, render
from civiccast_brief.site.urls import Urls

STATIC_DIR = Path(__file__).parent / "static"
MARKER = ".civiccast-site-output"
"""A file written into every build folder. A build only clears a folder that has it."""


@dataclass(frozen=True)
class BuildReport:
    out_dir: Path
    episodes: int
    stories: int
    excluded: tuple[tuple[str, str], ...]
    pages: tuple[str, ...]
    feed_items: int
    files_written: int


def prepare_output(out_dir: Path) -> None:
    if out_dir.exists() and not out_dir.is_dir():
        raise ValueError(f"{out_dir} exists and is not a folder")
    if out_dir.is_dir() and any(out_dir.iterdir()):
        if not (out_dir / MARKER).is_file():
            raise ValueError(
                f"{out_dir} is not empty and was not made by this builder. "
                "Choose an empty folder or a folder from an earlier build."
            )
        for child in out_dir.iterdir():
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / MARKER).write_text("Generated by civiccast_brief.site. Safe to rebuild.\n", "utf-8")


# Response headers for hosts that read a _headers file (Cloudflare Pages, Netlify).
# no-transform stops the host from rewriting pages or adding its own scripts. The only
# analytics script is the Cloudflare Web Analytics beacon the templates add themselves.
HEADERS_PATH = "/_headers"
REDIRECTS_PATH = "/_redirects"
HEADERS_FILE = "/*\n  Cache-Control: public, max-age=0, must-revalidate, no-transform\n"


def write_file(out_dir: Path, rel: str, data: str | bytes) -> None:
    target = out_dir / rel.lstrip("/")
    target.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, bytes):
        target.write_bytes(data)
    else:
        target.write_text(data, encoding="utf-8", newline="\n")


def _page_file(path: str) -> str:
    """/episodes/x/ -> episodes/x/index.html; / -> index.html."""
    return path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/")


def write_static(out_dir: Path) -> int:
    """Copy static/ (with fonts/) to /assets/ and write the PNG favicon. Returns the file count."""
    count = 0
    for source in sorted(STATIC_DIR.rglob("*")):
        if source.is_file():
            rel = source.relative_to(STATIC_DIR).as_posix()
            write_file(out_dir, f"assets/{rel}", source.read_bytes())
            count += 1
    write_file(out_dir, FAVICON_PNG, images.favicon_png())
    return count + 1


def _write_assets(site: SiteInput, out_dir: Path) -> int:
    count = write_static(out_dir)
    city = site.city
    if city.share_image_source is not None:
        share = city.share_image_source.read_bytes()
    else:
        share = images.share_png()
    write_file(out_dir, seo.share_image_path(city), share)
    count += 1
    if city.artwork_source is not None:
        art = city.artwork_source.read_bytes()
    else:
        art = images.artwork_png()
    write_file(out_dir, artwork_path(city), art)
    return count + 1


def build_site(
    episodes_dir: Path,
    out_dir: Path,
    base_url: str,
    *,
    now: datetime | None = None,
    fetch_still: stills.Fetch | None = None,
) -> BuildReport:
    """Build the site. Raises InputError for bad input and ValueError for an unsafe output folder.

    ``fetch_still`` downloads a meeting video's still image (see :mod:`stills`); without it only
    stills already in the cache folder are used."""
    urls = Urls.from_base(base_url)
    site = load_site_input(episodes_dir)
    if not site.episodes and not site.stories:
        raise InputError([f"{episodes_dir}: no approved episodes or stories to build"])
    stamp = now or datetime.now().astimezone()
    video_ids = [
        video_id
        for item in (*site.episodes, *site.stories)
        if (video_id := stills.youtube_id(item.video_url))
    ]
    found = stills.collect(video_ids, episodes_dir / stills.CACHE_DIR, fetch_still)
    still_paths = {video_id: stills.still_path(video_id) for video_id in found}
    pages, sitemap_paths = build_pages(site, urls, stamp, still_paths)
    prepare_output(out_dir)
    files = _write_assets(site, out_dir)
    for video_id, data in found.items():
        write_file(out_dir, still_paths[video_id], data)
        files += 1

    env = make_environment(urls)
    for spec in pages:
        context = {**spec.context, "scripts": list(spec.scripts)}
        html = render(env, spec.template, context)
        write_file(out_dir, _page_file(spec.path), html)
        files += 1

    write_file(out_dir, SITEMAP_PATH, seo.sitemap_xml(urls, sitemap_paths))
    write_file(out_dir, ROBOTS_PATH, seo.robots_txt(urls))
    write_file(out_dir, SEARCH_INDEX_PATH, seo.search_index_json(urls, site.episodes, site.stories))
    write_file(out_dir, "feed.xml", build_feed(site.city, urls, site.episodes, stamp))
    write_file(out_dir, HEADERS_PATH, HEADERS_FILE)
    files += 5
    if site.merged_stories:
        # Hosts that read a _redirects file send a story's old address to its episode page.
        lines = [
            f"{urls.page_path('stories', story_id)} {urls.page_path('episodes', story_id)} 301"
            for story_id in site.merged_stories
        ]
        write_file(out_dir, REDIRECTS_PATH, "\n".join(lines) + "\n")
        files += 1

    return BuildReport(
        out_dir=out_dir,
        episodes=len(site.episodes),
        stories=len(site.stories),
        excluded=site.excluded,
        pages=tuple(spec.path for spec in pages),
        feed_items=len(site.episodes),
        files_written=files,
    )
